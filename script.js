const grid = document.querySelector('#activities');
const moreButton = document.querySelector('#show-more');
const dialog = document.querySelector('#activity-dialog');
let currentFilter = 'all';
let expanded = false;
let lastTrigger;

function renderActivities() {
  const matches = activities.filter(item => currentFilter === 'all' || item.category === currentFilter);
  const visible = expanded ? matches : matches.slice(0, 6);
  grid.replaceChildren();
  visible.forEach(item => {
    const card = document.createElement('article');
    card.className = 'activity-card';
    const media = document.createElement('div');
    media.className = 'card-image';
    const img = document.createElement('img');
    img.src = item.images[0]; img.alt = item.title; img.loading = 'lazy';
    const tag = document.createElement('span');
    tag.className = 'card-tag'; tag.textContent = item.label;
    media.append(img, tag);
    const content = document.createElement('div');
    content.className = 'card-content';
    const title = document.createElement('h3'); title.textContent = item.title;
    const description = document.createElement('p'); description.textContent = item.summary;
    const button = document.createElement('button');
    button.type = 'button';
    button.setAttribute('aria-label', `Khám phá ${item.title}`);
    button.append('Khám phá hoạt động');
    const arrow = document.createElement('span'); arrow.textContent = '↗'; arrow.setAttribute('aria-hidden', 'true');
    button.append(arrow);
    button.addEventListener('click', () => openActivity(item, button));
    content.append(title, description, button);
    card.append(media, content);
    grid.append(card);
  });
  moreButton.hidden = expanded || matches.length <= 6;
  document.querySelector('#filter-status').textContent = `Hiển thị ${visible.length} trong ${matches.length} hoạt động.`;
}

function openActivity(item, trigger) {
  lastTrigger = trigger;
  document.querySelector('#dialog-title').textContent = item.title;
  document.querySelector('#dialog-category').textContent = item.label;
  document.querySelector('#dialog-description').textContent = item.description;
  const gallery = document.querySelector('#dialog-gallery');
  gallery.replaceChildren();
  item.images.forEach((path, i) => {
    const image = document.createElement('img');
    image.src = path; image.alt = `${item.title} – hình ảnh ${i + 1}`;
    image.loading = i === 0 ? 'eager' : 'lazy';
    gallery.append(image);
  });
  dialog.showModal(); dialog.scrollTop = 0;
  document.body.classList.add('modal-open');
}

document.querySelector('.dialog-close').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => {
  const rect = dialog.getBoundingClientRect();
  if (event.target === dialog && (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom)) dialog.close();
});
dialog.addEventListener('close', () => {
  document.body.classList.remove('modal-open'); lastTrigger?.focus();
});

document.querySelectorAll('[data-filter]').forEach(button => {
  button.addEventListener('click', () => {
    currentFilter = button.dataset.filter; expanded = false;
    document.querySelectorAll('[data-filter]').forEach(other => {
      const selected = other === button;
      other.classList.toggle('selected', selected);
      other.setAttribute('aria-pressed', String(selected));
    });
    renderActivities();
  });
});
moreButton.addEventListener('click', () => {
  const previousCount = grid.children.length;
  expanded = true; renderActivities();
  grid.children[previousCount]?.querySelector('button').focus({ preventScroll: true });
});

const menuButton = document.querySelector('.menu-toggle');
const navigation = document.querySelector('#navigation');
function closeMenu() {
  navigation.classList.remove('open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', 'Mở menu');
}
menuButton.addEventListener('click', () => {
  const open = navigation.classList.toggle('open');
  menuButton.setAttribute('aria-expanded', String(open));
  menuButton.setAttribute('aria-label', open ? 'Đóng menu' : 'Mở menu');
});
navigation.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
